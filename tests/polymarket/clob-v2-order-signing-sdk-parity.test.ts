/**
 * Blocker B (#272) — Offline EIP-712 parity, signed-vs-transport separation,
 * deterministic golden vectors, and negative verification tests against the
 * official `@polymarket/clob-client-v2` SDK (`OrderBuilder` / `orderToJsonV2`).
 *
 * Strictly offline: deterministic throwaway test keys only; zero real keys or live calls.
 */

import { describe, expect, it } from 'vitest';
import { ethers } from 'ethers';
import {
  OrderBuilder,
  Side,
  SignatureTypeV2,
  getContractConfig,
  orderToJsonV2,
} from '@polymarket/clob-client-v2';
import {
  CLOB_V2_EXCHANGE_POLYGON_ADDRESS,
  CLOB_V2_NEG_RISK_EXCHANGE_POLYGON_ADDRESS,
  CLOB_V2_ORDER_FIELD_TYPES,
  EXCHANGE_V2_DOMAIN_VERSION,
  POLYGON_CHAIN_ID,
  POLY_1271_SIGNATURE_TYPE,
  ZERO_BUILDER_CODE,
  ZERO_METADATA_BYTES32,
  buildClobV2TransportPayload,
  buildClobV2TypedData,
  computeClobV2OrderHash,
  signClobV2Order,
  verifyClobV2SignedOrder,
  type ClobV2ExchangeConfig,
  type ClobV2OrderIntent,
} from '../../src/desk/polymarket/clob-v2-order-surface';
import {
  Poly1271IsolationError,
  Poly1271SessionSigner,
} from '../../src/desk/polymarket/poly1271-session-signer';

const SESSION_PRIV_KEY =
  '0x0123456789012345678901234567890123456789012345678901234567890123';
const WRONG_PRIV_KEY =
  '0xabcdefabcdefabcdefabcdefabcdefabcdefabcdefabcdefabcdefabcdefabcd';
const DEPOSIT_WALLET = '0x1111111111111111111111111111111111111111';

describe('CLOB V2 EIP-712 SDK parity, golden vectors & negative tests (#272)', () => {
  it('matches @polymarket/clob-client-v2 contract addresses and 11-field EIP-712 Order struct byte-for-byte', async () => {
    const sdkContracts = getContractConfig(137);
    expect(CLOB_V2_EXCHANGE_POLYGON_ADDRESS).toBe(sdkContracts.exchangeV2);
    expect(CLOB_V2_NEG_RISK_EXCHANGE_POLYGON_ADDRESS).toBe(sdkContracts.negRiskExchangeV2);
    expect(EXCHANGE_V2_DOMAIN_VERSION).toBe('2');

    const sessionWallet = new ethers.Wallet(SESSION_PRIV_KEY);
    let capturedSdkDomain: ethers.TypedDataDomain | undefined;
    let capturedSdkTypes: Record<string, ethers.TypedDataField[]> | undefined;
    let capturedSdkMessage: Record<string, unknown> | undefined;

    const spySigner = {
      getAddress: () => Promise.resolve(sessionWallet.address),
      _signTypedData: async (
        domain: ethers.TypedDataDomain,
        types: Record<string, ethers.TypedDataField[]>,
        value: Record<string, unknown>,
      ) => {
        capturedSdkDomain = domain;
        capturedSdkTypes = types;
        capturedSdkMessage = value;
        return sessionWallet.signTypedData(domain, types, value);
      },
    };

    const sdkBuilder = new OrderBuilder(
      spySigner as never,
      POLYGON_CHAIN_ID,
      SignatureTypeV2.POLY_1271,
      DEPOSIT_WALLET,
    );
    const sdkOrder = await sdkBuilder.buildOrder(
      {
        tokenID: '98765432101234567890',
        price: 0.6,
        size: 10,
        side: Side.BUY,
        expiration: 1_800_000_000,
      },
      { tickSize: '0.01', negRisk: false },
      2,
    );

    expect(capturedSdkTypes?.Order).toEqual(CLOB_V2_ORDER_FIELD_TYPES);

    // Feed the exact salt & timestamp generated by the official SDK into our builder:
    const intent: ClobV2OrderIntent = {
      tokenId: '98765432101234567890',
      side: 'BUY',
      price: 0.6,
      size: 10,
      orderType: 'GTD',
      tickSize: 0.01,
      salt: sdkOrder.salt,
      timestamp: sdkOrder.timestamp,
      metadata: ZERO_METADATA_BYTES32,
      builderCode: ZERO_BUILDER_CODE,
      expiration: 1_800_000_000,
      postOnly: true,
    };
    const cfg: ClobV2ExchangeConfig = {
      verifyingContract: CLOB_V2_EXCHANGE_POLYGON_ADDRESS,
      domainVersion: '2',
      chainId: POLYGON_CHAIN_ID,
      signatureType: POLY_1271_SIGNATURE_TYPE,
      maker: DEPOSIT_WALLET,
      signer: sessionWallet.address,
    };

    const ourTyped = buildClobV2TypedData(intent, cfg);
    expect(ourTyped.domain).toEqual(capturedSdkDomain);
    expect(ourTyped.types).toEqual(capturedSdkTypes);
    expect(ourTyped.message).toEqual(capturedSdkMessage);

    const ourSigned = await signClobV2Order(sessionWallet, intent, cfg);
    expect(ourSigned.signature).toBe(sdkOrder.signature);

    // Verify signed vs transport field separation matches SDK `orderToJsonV2`
    expect('expiration' in ourTyped.message).toBe(false);
    expect('nonce' in ourTyped.message).toBe(false);
    expect('feeRateBps' in ourTyped.message).toBe(false);
    expect('orderType' in ourTyped.message).toBe(false);
    expect('postOnly' in ourTyped.message).toBe(false);

    const sdkTransport = orderToJsonV2(sdkOrder, 'api-key-owner-id', 'GTD' as never, true, false);
    const ourTransport = buildClobV2TransportPayload(ourSigned, {
      owner: 'api-key-owner-id',
      orderType: 'GTD',
      postOnly: true,
      deferExec: false,
    });
    expect(ourTransport).toEqual(sdkTransport);
  });

  it('pins deterministic offline golden vector for orderHash and ECDSA signature', async () => {
    const sessionWallet = new ethers.Wallet(SESSION_PRIV_KEY);
    const goldenIntent: ClobV2OrderIntent = {
      tokenId: '777000111222333444555',
      side: 'BUY',
      price: 0.45,
      size: 20,
      orderType: 'GTC',
      tickSize: 0.01,
      salt: '42424242',
      timestamp: '1760000000000',
      metadata: ZERO_METADATA_BYTES32,
      builderCode: ZERO_BUILDER_CODE,
      expiration: 0,
      nonce: '7',
    };
    const goldenCfg: ClobV2ExchangeConfig = {
      verifyingContract: CLOB_V2_EXCHANGE_POLYGON_ADDRESS,
      domainVersion: '2',
      chainId: POLYGON_CHAIN_ID,
      signatureType: POLY_1271_SIGNATURE_TYPE,
      maker: DEPOSIT_WALLET,
      signer: sessionWallet.address,
    };

    const first = await signClobV2Order(sessionWallet, goldenIntent, goldenCfg);
    const second = await signClobV2Order(sessionWallet, goldenIntent, goldenCfg);
    expect(first.orderHash).toBe(second.orderHash);
    expect(first.signature).toBe(second.signature);
    expect(first.orderHash).toBe(computeClobV2OrderHash(goldenIntent, goldenCfg));
    expect(first.orderHash).toMatch(/^0x[0-9a-f]{64}$/);

    const verification = verifyClobV2SignedOrder(first, goldenCfg, { nowSec: 1_760_000_000 });
    expect(verification).toEqual({ ok: true, recoveredSigner: sessionWallet.address });
  });

  it('rejects invalid signature, wrong signer, wrong chain, wrong nonce, and expired session/order', async () => {
    const sessionWallet = new ethers.Wallet(SESSION_PRIV_KEY);
    const wrongWallet = new ethers.Wallet(WRONG_PRIV_KEY);

    const intent: ClobV2OrderIntent = {
      tokenId: '555666777888',
      side: 'SELL',
      price: 0.72,
      size: 15,
      orderType: 'GTD',
      tickSize: 0.01,
      salt: '999888777',
      timestamp: '1760000000000',
      expiration: 1_760_003_600,
      nonce: '12',
    };
    const cfg: ClobV2ExchangeConfig = {
      verifyingContract: CLOB_V2_EXCHANGE_POLYGON_ADDRESS,
      domainVersion: '2',
      chainId: POLYGON_CHAIN_ID,
      signatureType: POLY_1271_SIGNATURE_TYPE,
      maker: DEPOSIT_WALLET,
      signer: sessionWallet.address,
    };

    const validSigned = await signClobV2Order(sessionWallet, intent, cfg);

    // 1. Corrupted / invalid signature bytes
    const corrupted = {
      ...validSigned,
      signature: `${validSigned.signature.slice(0, -4)}dead`,
    };
    const badSigRes = verifyClobV2SignedOrder(corrupted, cfg, { nowSec: 1_760_000_100 });
    expect(badSigRes.ok).toBe(false);
    if (!badSigRes.ok) {
      expect(['INVALID_SIGNATURE', 'WRONG_SIGNER']).toContain(badSigRes.code);
    }

    // 2. Signed by wrong key (attacker EOA != declared session signer)
    const wrongKeySig = await wrongWallet.signTypedData(
      buildClobV2TypedData(intent, cfg).domain,
      { Order: CLOB_V2_ORDER_FIELD_TYPES },
      buildClobV2TypedData(intent, cfg).message,
    );
    const wrongSignerRes = verifyClobV2SignedOrder(
      { ...validSigned, signature: wrongKeySig },
      cfg,
      { nowSec: 1_760_000_100 },
    );
    expect(wrongSignerRes).toEqual({
      ok: false,
      code: 'WRONG_SIGNER',
      detail: expect.stringContaining(wrongWallet.address),
    });

    // 3. Wrong chainId (e.g. signed for Amoy 80002, verified on Polygon 137)
    const amoySigned = await signClobV2Order(sessionWallet, intent, { ...cfg, chainId: 80002 });
    const wrongChainRes = verifyClobV2SignedOrder(amoySigned, cfg, { nowSec: 1_760_000_100 });
    expect(wrongChainRes.ok).toBe(false);
    if (!wrongChainRes.ok) {
      expect(['INVALID_SIGNATURE', 'WRONG_SIGNER']).toContain(wrongChainRes.code);
    }

    // 4. Wrong / replayed nonce against minimum session nonce floor + malformed non-numeric nonce
    const wrongNonceRes = verifyClobV2SignedOrder(validSigned, cfg, {
      nowSec: 1_760_000_100,
      expectedMinNonce: 13n,
    });
    expect(wrongNonceRes).toEqual({
      ok: false,
      code: 'WRONG_NONCE',
      detail: expect.stringContaining('12'),
    });
    const malformedNonceRes = verifyClobV2SignedOrder(
      { ...validSigned, order: { ...validSigned.order, nonce: '12abc' } },
      cfg,
      { nowSec: 1_760_000_100, expectedMinNonce: 1n },
    );
    expect(malformedNonceRes).toEqual({
      ok: false,
      code: 'WRONG_NONCE',
      detail: expect.stringContaining('12abc'),
    });

    // 5. Expired order / expired delegated session (including exact boundary nowSec === exp)
    const exactBoundaryOrderRes = verifyClobV2SignedOrder(validSigned, cfg, {
      nowSec: 1_760_003_600,
    });
    expect(exactBoundaryOrderRes.ok).toBe(false);
    if (!exactBoundaryOrderRes.ok) expect(exactBoundaryOrderRes.code).toBe('EXPIRED_ORDER');

    const exactBoundarySessionRes = verifyClobV2SignedOrder(validSigned, cfg, {
      nowSec: 1_760_000_400,
      sessionExpiresAtSec: 1_760_000_400,
    });
    expect(exactBoundarySessionRes).toEqual({
      ok: false,
      code: 'SESSION_EXPIRED',
      detail: expect.stringContaining('1760000400'),
    });

    // 6. Poly1271SessionSigner enforces session expiry fail-closed on exact boundary + defaults V2 domainVersion='2'
    const exactBoundarySessionSigner = new Poly1271SessionSigner({
      depositWalletAddress: DEPOSIT_WALLET,
      verifyingContract: CLOB_V2_EXCHANGE_POLYGON_ADDRESS,
      sessionPrivateKey: SESSION_PRIV_KEY,
      sessionExpiresAtSec: 1_700_000_000,
      nowSec: () => 1_700_000_000,
    });
    await expect(exactBoundarySessionSigner.signOrder(intent)).rejects.toThrow(Poly1271IsolationError);

    const activeV2SessionSigner = new Poly1271SessionSigner({
      depositWalletAddress: DEPOSIT_WALLET,
      verifyingContract: CLOB_V2_NEG_RISK_EXCHANGE_POLYGON_ADDRESS,
      sessionPrivateKey: SESSION_PRIV_KEY,
      sessionExpiresAtSec: 1_900_000_000,
      nowSec: () => 1_700_000_000,
    });
    const v2SessionSigned = await activeV2SessionSigner.signOrder({
      tokenId: '555666777888',
      side: 'BUY',
      price: 0.45,
      size: 10.123,
      orderType: 'GTC',
      tickSize: 0.01,
      salt: '888777666',
      timestamp: '1760000000000',
    });
    const verifiedSessionOrder = verifyClobV2SignedOrder(v2SessionSigned, {
      verifyingContract: CLOB_V2_NEG_RISK_EXCHANGE_POLYGON_ADDRESS,
    });
    expect(verifiedSessionOrder).toEqual({ ok: true, recoveredSigner: sessionWallet.address });
  });

  it('matches @polymarket/clob-client-v2 fractional size truncation & tick rounding across all 4 tick sizes and prevents verifier/transport split-brain', async () => {
    const sessionWallet = new ethers.Wallet(SESSION_PRIV_KEY);
    const sdkSigner = {
      getAddress: async () => sessionWallet.address,
      _signTypedData: async (
        domain: ethers.TypedDataDomain,
        types: Record<string, ethers.TypedDataField[]>,
        value: Record<string, unknown>,
      ) => sessionWallet.signTypedData(domain, types, value),
    };
    const sdkBuilder = new OrderBuilder(
      sdkSigner as never,
      POLYGON_CHAIN_ID,
      SignatureTypeV2.POLY_1271,
      DEPOSIT_WALLET,
    );

    const vectors: Array<{ tickSize: '0.1' | '0.01' | '0.001' | '0.0001'; price: number; size: number; side: 'BUY' | 'SELL' }> = [
      { tickSize: '0.1', price: 0.3, size: 10.159, side: 'BUY' },
      { tickSize: '0.01', price: 0.45, size: 10.123, side: 'BUY' },
      { tickSize: '0.01', price: 0.57, size: 5.29, side: 'SELL' },
      { tickSize: '0.001', price: 0.333, size: 10.179, side: 'BUY' },
      { tickSize: '0.0001', price: 0.4321, size: 7.899, side: 'SELL' },
    ];

    for (const vec of vectors) {
      const sdkSigned = await sdkBuilder.buildOrder(
        {
          tokenID: '998877665544',
          price: vec.price,
          size: vec.size,
          side: vec.side === 'BUY' ? Side.BUY : Side.SELL,
        },
        { tickSize: vec.tickSize, negRisk: false },
        2,
      );
      const ourSigned = await signClobV2Order(
        sessionWallet,
        {
          tokenId: '998877665544',
          side: vec.side,
          price: vec.price,
          size: vec.size,
          orderType: 'GTC',
          tickSize: Number(vec.tickSize),
          salt: sdkSigned.salt,
          timestamp: sdkSigned.timestamp,
          metadata: sdkSigned.metadata,
          builderCode: sdkSigned.builder,
        },
        {
          verifyingContract: CLOB_V2_EXCHANGE_POLYGON_ADDRESS,
          maker: DEPOSIT_WALLET,
          signer: sessionWallet.address,
        },
      );
      expect(ourSigned.signedMessage.makerAmount).toBe(sdkSigned.makerAmount);
      expect(ourSigned.signedMessage.takerAmount).toBe(sdkSigned.takerAmount);
      expect(ourSigned.signature).toBe(sdkSigned.signature);

      const transport = buildClobV2TransportPayload(ourSigned, { owner: 'api-key-1' });
      expect(transport.order.side).toBe(vec.side);
      expect(transport.deferExec).toBe(false);
      expect(transport.postOnly).toBe(false);
    }

    // Split-brain / tampered signedMessage or orderHash + unsafe transport salts
    const sample = await signClobV2Order(
      sessionWallet,
      {
        tokenId: '998877665544',
        side: 'BUY',
        price: 0.5,
        size: 10,
        orderType: 'GTC',
        tickSize: 0.01,
        salt: '12345',
        timestamp: '1760000000000',
      },
      { verifyingContract: CLOB_V2_EXCHANGE_POLYGON_ADDRESS },
    );
    expect(
      verifyClobV2SignedOrder(
        { ...sample, signedMessage: { ...sample.signedMessage, makerAmount: '1' } },
        { verifyingContract: CLOB_V2_EXCHANGE_POLYGON_ADDRESS },
      ),
    ).toEqual({
      ok: false,
      code: 'INVALID_SIGNATURE',
      detail: expect.stringContaining('signedMessage'),
    });
    expect(
      verifyClobV2SignedOrder(
        { ...sample, orderHash: `0x${'00'.repeat(32)}` },
        { verifyingContract: CLOB_V2_EXCHANGE_POLYGON_ADDRESS },
      ),
    ).toEqual({
      ok: false,
      code: 'INVALID_SIGNATURE',
      detail: expect.stringContaining('orderHash'),
    });
    expect(
      verifyClobV2SignedOrder(sample, { verifyingContract: 'not-an-address' }),
    ).toEqual({
      ok: false,
      code: 'INVALID_SIGNATURE',
      detail: expect.any(String),
    });
    expect(
      verifyClobV2SignedOrder(sample, { verifyingContract: CLOB_V2_EXCHANGE_POLYGON_ADDRESS }, { expectedMinNonce: 0n }),
    ).toEqual({ ok: true, recoveredSigner: sessionWallet.address });

    expect(() =>
      buildClobV2TransportPayload(
        { ...sample, signedMessage: { ...sample.signedMessage, salt: '42abc' } },
        { owner: 'k' },
      ),
    ).toThrow(/Unsafe V2 transport salt/);
    expect(() =>
      buildClobV2TransportPayload(
        { ...sample, signedMessage: { ...sample.signedMessage, salt: '9007199254740993' } },
        { owner: 'k' },
      ),
    ).toThrow(/Unsafe V2 transport salt/);
  });
});
